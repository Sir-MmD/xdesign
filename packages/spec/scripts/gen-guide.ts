// make gen-guide, a step of make gen (docs/plan/06-export-and-claude-link.md section 4): reads
// packages/spec/docs/HOW-TO-READ.md on stdin and prints it as the TypeScript module of HOW_TO_READ,
// which the Makefile writes to packages/spec/src/markdown/how-to-read.gen.ts, so the browser and
// the server put the guide in every export without reading files. The module is committed and make
// sanity's drift check compares it with a fresh make gen.
const chunks: string[] = []
process.stdin.setEncoding('utf8')
for await (const chunk of process.stdin) chunks.push(String(chunk))

// A template literal of the text: backslashes, backticks and `${` escaped.
const literal = chunks.join('').replace(/\\|`|\$\{/g, (match) => `\\${match}`)

process.stdout.write(
  [
    '// Generated by make gen-guide from packages/spec/docs/HOW-TO-READ.md: edit that file, then run',
    '// make gen.',
    '',
    '/** HOW-TO-READ.md, the guide for builders copied into every export (06 section 4). */',
    `export const HOW_TO_READ = \`${literal}\``,
    '',
  ].join('\n'),
)
