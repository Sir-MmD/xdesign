/** Every limit of the catalog. */
export const LIMITS = [...OWN_LIMITS, ...KEYBOARD_SIZE_LIMITS, ...UPLOAD_LIMITS] as const

export type LimitId = (typeof LIMITS)[number]['id']

const limitsById = new Map<string, LimitRow>(LIMITS.map((row) => [row.id, row]))

/** The limit row of an id. */
export function limit<Id extends LimitId>(id: Id): Extract<(typeof LIMITS)[number], { id: Id }> {
  const row = limitsById.get(id)
  if (!row) throw new Error(`no limit ${id}`)
  return row as Extract<(typeof LIMITS)[number], { id: Id }>
}
