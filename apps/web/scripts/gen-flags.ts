// make gen-flags, a step of make gen (docs/plan/16 section 3, FLAG-01): prints the flag-icons
// stylesheet of the flags the language list uses (each language's `flag` in src/lib/languages.ts),
// instead of all of flag-icons' flags, as xWriter's tools/gen-languages writes its flags.gen.css.
// The Makefile writes it to src/styles/flags.gen.css, which LanguageFlag's module imports; the file
// is committed and make sanity's drift check compares it with a fresh make gen.
import { existsSync } from 'node:fs'
import { resolve } from 'node:path'

import { languages } from '../src/lib/languages.ts'

const flagsDir = resolve(import.meta.dirname, '../node_modules/flag-icons/flags/4x3')

const flags = [...new Set(languages.flatMap((language) => (language.flag === undefined ? [] : [language.flag])))].sort()
for (const flag of flags) {
  if (!existsSync(resolve(flagsDir, `${flag}.svg`))) throw new Error(`gen-flags: flag-icons has no flag ${flag}`)
}

// flag-icons' base rules (css/flag-icons.css) and one rule per flag, the path from src/styles/.
process.stdout.write(
  [
    '/* Generated by make gen-flags from apps/web/src/lib/languages.ts: the flag-icons rules of the\n' +
      '   flags the language list uses, instead of all of them (FLAG-01, docs/plan/16 section 3).\n' +
      '   Edit the `flag` fields there, then run make gen. */\n',
    '.fi {\n  background-size: contain;\n  background-position: 50%;\n  background-repeat: no-repeat;\n' +
      '  position: relative;\n  display: inline-block;\n  width: 1.333333em;\n  line-height: 1em;\n}\n',
    ".fi::before {\n  content: '\\00a0';\n}\n",
    ...flags.map(
      (flag) => `.fi-${flag} {\n  background-image: url('../../node_modules/flag-icons/flags/4x3/${flag}.svg');\n}\n`,
    ),
  ].join('\n'),
)
